KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


# Response types ----------------------------------------------------------------


def doc_type(t: T, ns: str = "") -> str:
    """PHPStan type of a response value, without the nullable part of ``t`` itself."""
    if isinstance(t, Scalar):
        return t.php
    if isinstance(t, DateTimeT):
        return "\\DateTimeImmutable"
    if isinstance(t, EnumT):
        return t.enum.base
    if isinstance(t, ModelT):
        return ns + t.model.name
    if isinstance(t, ArrayT):
        item = doc_type(t.item, ns)
        if t.item.nullable and not isinstance(t.item, AnyT):
            item += "|null"
        return f"list<{item}>"
    if isinstance(t, MapT):
        return f"array<string, {doc_type(t.value, ns)}>"
    if isinstance(t, FreeObjT):
        return "array<string, mixed>"
    if isinstance(t, UnionT):
        return "|".join(dict.fromkeys(doc_type(v, ns) for v in _union_order(t.variants)))
    return "mixed"


def native_type(t: T) -> str:
    """Native PHP property type (always nullable)."""
    if isinstance(t, Scalar):
        return "?" + t.php
    if isinstance(t, DateTimeT):
        return "?\\DateTimeImmutable"
    if isinstance(t, EnumT):
        return "?" + t.enum.base
    if isinstance(t, ModelT):
        return "?" + t.model.name
    if isinstance(t, (ArrayT, MapT, FreeObjT)):
        return "?array"
    if isinstance(t, UnionT):
        natives = []
        for v in t.variants:
            n = native_type(v)
            if n == "mixed":
                return "mixed"
            natives.append(n.lstrip("?"))
        uniq = list(dict.fromkeys(natives))
        if len(uniq) == 1:
            return "?" + uniq[0]
        return "|".join(uniq) + "|null"
    return "mixed"


def _union_order(variants: list[T]) -> list[T]:
    def rank(v: T) -> int:
        if isinstance(v, (ModelT, MapT, FreeObjT)):
            return 0
        if isinstance(v, ArrayT):
            return 1
        return 2

    return sorted(variants, key=rank)


def hydrate(t: T, value: str, ns: str = "") -> str:
    """Expression converting decoded JSON ``value`` into the property type."""
    if isinstance(t, Scalar):
        return f"Hydrate::{t.php}({value})"
    if isinstance(t, DateTimeT):
        return f"Hydrate::dateTime({value})"
    if isinstance(t, EnumT):
        return f"Hydrate::{t.enum.base}({value})"
    if isinstance(t, ModelT):
        return f"Hydrate::model({value}, {ns}{t.model.name}::class)"
    if isinstance(t, ArrayT):
        fn = "nullableList" if t.item.nullable and not isinstance(t.item, AnyT) else "list"
        return f"Hydrate::{fn}({value}, {callable_for(t.item, ns)})"
    if isinstance(t, MapT):
        return f"Hydrate::map({value}, {callable_for(t.value, ns)})"
    if isinstance(t, FreeObjT):
        return f"Hydrate::assoc({value})"
    if isinstance(t, UnionT):
        parts = [hydrate(v, value, ns) for v in _union_order(t.variants)]
        return " ?? ".join(parts)
    return f"Hydrate::mixed({value})"


def callable_for(t: T, ns: str = "") -> str:
    if isinstance(t, Scalar):
        return f"Hydrate::{t.php}(...)"
    if isinstance(t, DateTimeT):
        return "Hydrate::dateTime(...)"
    if isinstance(t, EnumT):
        return f"Hydrate::{t.enum.base}(...)"
    if isinstance(t, FreeObjT):
        return "Hydrate::assoc(...)"
    if isinstance(t, AnyT):
        return "Hydrate::mixed(...)"
    return f"static fn (mixed $v) => {hydrate(t, '$v', ns)}"


# Request shapes -------------------------------------------------------------------


FILE_TYPE = "\\Didit\\File|\\Psr\\Http\\Message\\StreamInterface|resource"


def shape_type(t: T) -> str:
    if isinstance(t, Scalar):
        return {"float": "float|int"}.get(t.php, t.php) + ("|null" if t.nullable else "")
    if isinstance(t, DateTimeT):
        out = "\\DateTimeInterface|string"
    elif isinstance(t, EnumT):
        out = t.enum.base
    elif isinstance(t, ShapeT):
        out = t.shape.name
    elif isinstance(t, ModelT):  # never used for requests
        out = "array<string, mixed>"
    elif isinstance(t, ArrayT):
        out = f"list<{shape_type(t.item)}>"
    elif isinstance(t, MapT):
        out = f"array<string, {shape_type(t.value)}>"
    elif isinstance(t, FreeObjT):
        out = "array<string, mixed>"
    elif isinstance(t, FileT):
        out = FILE_TYPE
    elif isinstance(t, UnionT):
        out = "|".join(dict.fromkeys(shape_type(v) for v in t.variants))
    else:
        return "mixed"
    if t.nullable and "null" not in out.split("|"):
        out += "|null"
    return out


def shape_key(key: str) -> str:
    return key if KEY_RE.match(key) else php_string(key)


def array_shape(fields: list[tuple[str, str, bool]], indent: str) -> list[str]:
    """Multi-line ``array{...}`` lines; ``fields`` are (key, type, required)."""
    if not fields:
        return ["array<string, mixed>"]
    lines = ["array{"]
    for key, typ, required in fields:
        lines.append(f"{indent}    {shape_key(key)}{'' if required else '?'}: {typ},")
    lines.append(f"{indent}}}")
    return lines


def json_hint(t: T) -> list | None:
    """Where a request value is a JSON object, so an empty PHP array is sent as ``{}``.

    ``['o', {key: hint}]`` object (children optional), ``['m', hint]`` map,
    ``['l', hint]`` list whose items need hints. None: nothing to do.
    """
    if isinstance(t, ShapeT):
        children = {p.wire: h for p in t.shape.props if (h := json_hint(p.type)) is not None}
        return ["o", children] if children else ["o"]
    if isinstance(t, MapT):
        value = json_hint(t.value)
        return ["m", value] if value is not None else ["o"]
    if isinstance(t, FreeObjT):
        return ["o"]
    if isinstance(t, ArrayT):
        item = json_hint(t.item)
        return ["l", item] if item is not None else None
    if isinstance(t, UnionT):
        for v in t.variants:
            h = json_hint(v)
            if h is not None:
                return h
    return None


def php_hint(value) -> str:
    if isinstance(value, list):
        return "[" + ", ".join(php_hint(v) for v in value) + "]"
    if isinstance(value, dict):
        return "[" + ", ".join(f"{php_string(k)} => {php_hint(v)}" for k, v in value.items()) + "]"
    return php_string(str(value))


# Files ------------------------------------------------------------------------------


@dataclass
class Output:
    files: dict[str, str] = field(default_factory=dict)

    def add(self, path: str, content: str) -> None:
        if path in self.files:
            raise ValueError(f"generated twice: {path}")
        self.files[path] = content


def emit_enum(enum: Enum) -> str:
    lines = [HEADER, "namespace Didit\\Types;", ""]
    desc = first_paragraph(enum.description)
    doc = []
    if desc:
        doc += wrap(desc)
        doc.append("")
    doc.append("Known values. The API may add values: compare with these constants and keep a default branch.")
    lines.append(docblock(doc).rstrip("\n"))
    lines.append(f"final class {enum.name}")
    lines.append("{")
    used: set[str] = set()
    for value in enum.values:
        const = naming.enum_constant(value, used)
        literal = php_string(value) if isinstance(value, str) else str(value)
        lines.append(f"    public const {const} = {literal};")
        lines.append("")
    lines.append("    private function __construct()")
    lines.append("    {")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_model(model: Model) -> str:
    lines = [HEADER, "namespace Didit\\Types;", "", "use Didit\\Core\\BaseModel;"]
    if model.props:
        lines.append("use Didit\\Core\\Hydrate;")
    lines.append("")
    desc = first_paragraph(model.description)
    doc = wrap(desc) if desc else [f"{model.name}."]
    lines.append(docblock(doc).rstrip("\n"))
    lines.append(f"final class {model.name} extends BaseModel")
    lines.append("{")
    for prop in model.props:
        lines.append(_property_doc(prop).rstrip("\n"))
        lines.append(f"    public readonly {native_type(prop.type)} ${prop.name};")
        lines.append("")
    lines.append("    /**")
    lines.append("     * @param array<string, mixed> $data the decoded JSON object")
    lines.append("     */")
    lines.append("    public function __construct(array $data)")
    lines.append("    {")
    lines.append("        parent::__construct($data);")
    for prop in model.props:
        lines.append(f"        $this->{prop.name} = {hydrate(prop.type, '$data[' + php_string(prop.wire) + '] ?? null')};")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _property_doc(prop) -> str:
    desc = first_paragraph(prop.description)
    doc: list[str] = []
    if desc:
        doc += wrap(desc)
    if isinstance(prop.type, EnumT):
        if doc:
            doc.append("")
        doc.append(f"Known values: {{@see {prop.type.enum.name}}}.")
    native = native_type(prop.type)
    phpdoc = doc_type(prop.type)
    needs_var = phpdoc.split("|") != [native.lstrip("?")] and native != "mixed" or isinstance(prop.type, UnionT)
    if isinstance(prop.type, (ArrayT, MapT, FreeObjT)):
        needs_var = True
    if needs_var:
        if doc:
            doc.append("")
        nullable_doc = phpdoc if native == "mixed" else phpdoc + "|null"
        doc.append(f"@var {nullable_doc}")
    if prop.deprecated:
        if doc:
            doc.append("")
        doc.append("@deprecated")
    if not doc:
        doc = [sentence(f"The `{prop.wire}` field")]
    if len(doc) == 1:
        return f"    /** {doc[0]} */\n"
    return docblock(doc, "    ")


def emit_params(shapes: list[Shape], op_aliases: list[tuple[str, list[tuple[str, str, bool]]]]) -> str:
    lines = [HEADER, "namespace Didit;", ""]
    doc = [
        "Request parameter shapes for every operation, as PHPStan type aliases.",
        "",
        "Import one in your own code with",
        "`@phpstan-import-type SessionsCreateParams from \\Didit\\Params`.",
        "",
    ]
    entries: list[tuple[str, list[str]]] = []
    for name, fields in op_aliases:
        entries.append((name, array_shape(fields, "")))
    for shape in shapes:
        fields = [(p.wire, shape_type(p.type), p.required) for p in shape.props]
        entries.append((shape.name, array_shape(fields, "")))
    entries.sort(key=lambda e: e[0])
    for name, body in entries:
        doc.append(f"@phpstan-type {name} {body[0]}")
        doc.extend(body[1:])
    lines.append(docblock(doc).rstrip("\n"))
    lines.append("final class Params")
    lines.append("{")
    lines.append("    private function __construct()")
    lines.append("    {")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


# Resources ---------------------------------------------------------------------


@dataclass
class ResourceNode:
    path: str  # dot path
    children: dict[str, "ResourceNode"] = field(default_factory=dict)
    ops: list[OpModel] = field(default_factory=list)

    @property
    def segment(self) -> str:
        return self.path.rsplit(".", 1)[-1]

    @property
    def fqcn(self) -> str:
        return "Didit\\Resources\\" + naming.resource_class(self.path)

    @property
    def namespace(self) -> str:
        return self.fqcn.rsplit("\\", 1)[0]

    @property
    def short(self) -> str:
        return self.fqcn.rsplit("\\", 1)[1]


def resource_tree(ops: list[OpModel]) -> ResourceNode:
    root = ResourceNode("")
    for om in ops:
        node = root
        parts = om.op.naming.resource.split(".")
        for i in range(len(parts)):
            path = ".".join(parts[: i + 1])
            node = node.children.setdefault(parts[i], ResourceNode(path))
        node.ops.append(om)
    return root


def walk(node: ResourceNode):
    for child in node.children.values():
        yield child
        yield from walk(child)


def return_type(r: Response) -> tuple[str, str | None]:
    """(native return type, @return phpdoc or None)."""
    if r.kind == "model":
        assert isinstance(r.type, ModelT)
        return "Types\\" + r.type.model.name, None
    if r.kind == "page":
        return "Page", f"Page<{_item_doc(r.type)}>"
    if r.kind == "list":
        return "ListResponse", f"ListResponse<{_item_doc(r.type)}>"
    if r.kind == "json":
        return "JsonResponse", None
    if r.kind == "binary":
        return "BinaryContent", None
    if r.kind == "none":
        return "NoContent", None
    if r.kind == "union":
        natives = [return_type(v)[0] for v in r.variants]
        return "|".join(dict.fromkeys(natives)), None
    raise ValueError(r.kind)


def _item_doc(t: T | None) -> str:
    assert t is not None
    if isinstance(t, ModelT):
        return "Types\\" + t.model.name
    return doc_type(t, "Types\\")


def _response_expr(r: Response, var: str = "$response") -> str:
    if r.kind == "model":
        assert isinstance(r.type, ModelT)
        return f"Types\\{r.type.model.name}::fromResponse({var})"
    if r.kind == "list":
        return f"ListResponse::fromResponse({var}, {callable_for(r.type, TYPES_NS)})"
    if r.kind == "json":
        return f"JsonResponse::fromResponse({var})"
    if r.kind == "binary":
        return f"BinaryContent::fromResponse({var})"
    if r.kind == "none":
        return f"NoContent::fromResponse({var})"
    raise ValueError(r.kind)


def emit_resource(node: ResourceNode) -> str:
    imports = {"Didit\\Core\\BaseResource"}
    body: list[str] = []
    used_aliases: list[str] = []

    for child_name, child in node.children.items():
        body.append(f"    public readonly {_relative(node, child)} ${naming.camel(child_name)};")
        body.append("")
    if node.children:
        imports.add("Didit\\Core\\Requester")
        body.append("    public function __construct(Requester $requester)")
        body.append("    {")
        body.append("        parent::__construct($requester);")
        for child_name, child in node.children.items():
            body.append(f"        $this->{naming.camel(child_name)} = new {_relative(node, child)}($requester);")
        body.append("    }")
        body.append("")

    for om in node.ops:
        method_lines, method_imports, alias = _emit_method(om)
        imports |= method_imports | {"Didit\\Exception\\DiditException", "Didit\\RequestOptions", "Didit\\Core\\Operation"}
        if alias and alias not in used_aliases:
            used_aliases.append(alias)
        body.extend(method_lines)
        body.append("")
    while body and body[-1] == "":
        body.pop()
    if used_aliases:
        imports.add("Didit\\Params")

    lines = [HEADER, f"namespace {node.namespace};", ""]
    for imp in sorted(imports, key=lambda s: s.lower()):
        lines.append(f"use {imp};")
    lines.append("")
    doc = [sentence(f"The `{node.path}` resource")]
    if used_aliases:
        doc.append("")
        for alias in sorted(used_aliases):
            doc.append(f"@phpstan-import-type {alias} from Params")
    lines.append(docblock(doc).rstrip("\n"))
    lines.append(f"final class {node.short} extends BaseResource")
    lines.append("{")
    traits = CORE_TRAITS.get(node.path, [])
    for trait in traits:
        lines.append(f"    use {trait};")
    if traits and body:
        lines.append("")
    lines.extend(body)
    lines.append("}")
    return "\n".join(lines) + "\n"


def _relative(parent: ResourceNode, child: ResourceNode) -> str:
    # Child classes live in the namespace named after the parent class.
    return f"{parent.short}\\{child.short}" if parent.path else child.short


def _emit_method(om: OpModel) -> tuple[list[str], set[str], str | None]:
    o = om.op
    imports: set[str] = set()
    has_types = False
    lines: list[str] = []
    method = naming.camel(o.naming.method)

    # Docblock
    doc: list[str] = []
    summary = sentence(o.op.get("summary", "")) if o.op.get("summary") else sentence(f"{o.http_method} {o.path}")
    doc += wrap(summary)
    desc = first_paragraph(o.op.get("description"))
    if desc and desc.rstrip(".") != summary.rstrip("."):
        doc.append("")
        doc += wrap(desc)
    doc.append("")
    doc.append(f"`{o.http_method} {o.path}`")
    doc.append("")
    for pp in om.path_params:
        pdesc = annotation_text(first_sentence(pp.description))
        if pdesc:
            doc.append(f"@param {pp.php} ${pp.var} {pdesc}")
    if om.body_alias:
        doc.append(f"@param {om.body_alias} $params")
    native_ret, ret_doc = return_type(om.response)
    if ret_doc:
        doc.append("")
        doc.append(f"@return {ret_doc}")
    doc.append("")
    doc.append("@throws DiditException")
    if o.deprecated or o.op.get("deprecated"):
        doc.append("")
        if o.deprecated:
            doc.append(f"@deprecated This operation was removed from the API{(' on ' + o.removed_note) if o.removed_note else ''}; this method will be deleted in the next minor version.")
        else:
            doc.append("@deprecated The API marks this operation as deprecated.")
    lines.append(docblock(doc, "    ").rstrip("\n"))

    args = [f"{pp.php} ${pp.var}" for pp in om.path_params]
    has_params = om.body_alias is not None
    if has_params:
        required = _params_required(om)
        args.append("array $params" + ("" if required else " = []"))
    args.append("?RequestOptions $options = null")
    if "Types\\" in native_ret:
        has_types = True
    for kind in ("Page", "ListResponse", "JsonResponse", "BinaryContent", "NoContent"):
        if kind in native_ret.split("|"):
            imports.add(f"Didit\\Core\\{kind}")
    signature = f"    public function {method}({', '.join(args)}): {native_ret}"
    if len(signature) > 120:
        lines.append(f"    public function {method}(")
        for a in args:
            lines.append(f"        {a},")
        lines.append(f"    ): {native_ret} {{")
    else:
        lines.append(signature)
        lines.append("    {")

    op_args = [f"method: {php_string(o.http_method)}", f"path: {php_string(o.path)}"]
    if o.naming.auth != "api_key":
        op_args.append(f"auth: {php_string(o.naming.auth)}")
    if o.naming.scope == "application":
        op_args.append("applicationScope: true")
    if o.base == "account":
        op_args.append("base: 'account'")
    query = [p for p in om.params if p.location == "query"]
    headers = [p for p in om.params if p.location == "header"]
    if query:
        op_args.append("query: [" + ", ".join(f"{php_string(p.key)} => {php_string(p.wire)}" for p in query) + "]")
    if headers:
        op_args.append("headers: [" + ", ".join(f"{php_string(p.key)} => {php_string(p.wire)}" for p in headers) + "]")
    if om.body_types:
        op_args.append("bodyTypes: [" + ", ".join(php_string(b) for b in om.body_types) + "]")
    if om.body is not None:
        hints = {p.wire: h for p in om.body.props if (h := json_hint(p.type)) is not None}
        if hints:
            op_args.append(f"jsonHints: {php_hint(hints)}")
    if om.accept != "application/json":
        op_args.append(f"accept: {php_string(om.accept)}")
    operation = "new Operation(\n" + "".join(f"            {a},\n" for a in op_args) + "        )"
    path_arr = "[" + ", ".join(f"{php_string(pp.wire)} => ${pp.var}" for pp in om.path_params) + "]"
    params_var = "$params" if has_params else "[]"

    r = om.response
    if r.kind == "page":
        lines.append(f"        return $this->requester->requestPage({operation}, {path_arr}, {params_var}, $options, {callable_for(r.type, TYPES_NS)});")
        if isinstance(r.type, ModelT):
            has_types = True
    else:
        lines.append(f"        $response = $this->requester->request({operation}, {path_arr}, {params_var}, $options);")
        lines.append("")
        if r.kind == "union":
            lines.append("        return match ($response->status) {")
            default = r.variants[0]
            for v in r.variants[1:]:
                lines.append(f"            {int(v.status)} => {_response_expr(v)},")
            lines.append(f"            default => {_response_expr(default)},")
            lines.append("        };")
            has_types = True
        else:
            lines.append(f"        return {_response_expr(r)};")
            if r.kind == "list":
                imports.add("Didit\\Core\\Hydrate")
                if isinstance(r.type, ModelT):
                    has_types = True
    lines.append("    }")
    text = "\n".join(lines)
    if "Hydrate::" in text:
        imports.add("Didit\\Core\\Hydrate")
    if "Types\\" in text:
        imports.add("Didit\\Types")
    return lines, imports, om.body_alias


def _params_required(om: OpModel) -> bool:
    if any(p.required for p in om.params):
        return True
    if om.body is not None and om.body_required and any(p.required for p in om.body.props):
        return True
    return False


def op_alias_fields(om: OpModel) -> list[tuple[str, str, bool]]:
    fields: list[tuple[str, str, bool]] = []
    if om.body is not None:
        for p in om.body.props:
            fields.append((p.wire, shape_type(p.type), p.required and om.body_required))
    for p in om.params:
        fields.append((p.key, shape_type(p.type), p.required))
    return fields


def emit_client(root: ResourceNode) -> str:
    lines = [HEADER, "namespace Didit;", "", "use Didit\\Core\\BaseClient;", ""]
    doc = [
        "The Didit API client.",
        "",
        "```php",
        "$didit = new \\Didit\\DiditClient(apiKey: getenv('DIDIT_API_KEY'));",
        "$session = $didit->sessions->create(['workflow_id' => '...']);",
        "```",
        "",
        "Constructor options are documented on {@see BaseClient::__construct()}.",
    ]
    lines.append(docblock(doc).rstrip("\n"))
    lines.append("final class DiditClient extends BaseClient")
    lines.append("{")
    for name, child in root.children.items():
        lines.append(f"    public readonly Resources\\{child.short} ${naming.camel(name)};")
        lines.append("")
    lines.append("    protected function initResources(): void")
    lines.append("    {")
    for name, child in root.children.items():
        lines.append(f"        $this->{naming.camel(name)} = new Resources\\{child.short}($this->requester);")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"
